export type Lang = 'ru' | 'en' | 'es';

type InteractionLocale = {
  channel_id?: string;
  channel?: { parent_id?: string | null };
  locale?: string;
};

export function parseChannelLangs(value?: string): Map<string, Lang> {
  const channels = new Map<string, Lang>();
  for (const entry of (value || '').split(',')) {
    const match = /^([0-9]{5,25}):(ru|en|es)$/.exec(entry.trim());
    if (match) channels.set(match[1], match[2] as Lang);
  }
  return channels;
}

export function pickLang(interaction: InteractionLocale, channelLangs: ReadonlyMap<string, Lang>): Lang {
  for (const id of [interaction.channel_id, interaction.channel?.parent_id]) {
    if (id && channelLangs.has(id)) return channelLangs.get(id)!;
  }
  const locale = interaction.locale?.toLowerCase();
  if (!locale) return 'ru';
  if (/^(ru|uk|be)(-|$)/.test(locale)) return 'ru';
  return locale.startsWith('es') ? 'es' : 'en';
}

export const siteForLang = (site: string, lang: Lang) =>
  `${site.replace(/\/$/, '')}${lang === 'ru' ? '' : `/${lang}`}`;

export function localizedPath(path: string, lang: Lang): string {
  const plain = path.replace(/^\/(?:en|es)(?=\/)/, '');
  return `${lang === 'ru' ? '' : `/${lang}`}${plain}`;
}

export function localizedDataUrl(url: string, lang: Lang): string {
  return lang === 'ru' ? url : url.replace('/data/', `/${lang}/data/`);
}

